import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const migrationsRoot = join(root, 'drizzle')
const outFile = join(root, 'src', 'store', 'migrations.ts')

const folders = readdirSync(migrationsRoot)
  .filter(name => existsSync(join(migrationsRoot, name, 'migration.sql')))
  .sort()

const entries = folders.map(name => {
  const sql = readFileSync(join(migrationsRoot, name, 'migration.sql'), 'utf8')
  return `    { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(sql)} },`
})

const content = `// Generated by scripts/generate-migrations.mjs — do not edit.
// Run "pnpm db:generate" (or this script) after "drizzle-kit generate".

export interface BundledMigration {
    name: string;
    sql: string;
}

export const migrations: BundledMigration[] = [
${entries.join('\n')}
];
`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, content)
console.log(`wrote ${outFile} (${folders.length} migrations)`)
